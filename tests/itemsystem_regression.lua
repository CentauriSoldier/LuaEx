if not LUAEX_INIT then require("LuaEx.init") end
local Item = class("HolisticItem", {}, {}, {}, {}, {
    HolisticItem = function(this, cdat, super, tInput)
        local t = tInput or {};
        super("Item", "Integration test", nil, nil,
              t.attach,t.consume,t.damage,t.detach,t.equip,t.scope,t.conflicts,nil,t.remove,t.repair,
              t.storage or Registry({ItemSystem, ItemStashSystem}),t.tradeBy,t.tradeTo,t.unequip,t.upgrade,t.downgrade,
              nil,nil,nil,nil,nil,nil,t.pattern);
    end,
}, BaseItem);
local stash = ItemStashSystem(nil, 2, 3);
local first, second = stash.getTab(1), stash.getTab(2);
local kite = Item({scope = Registry({stash}), conflicts = Registry({Item})});
local other = Item();
assert(first.addItem(kite));
assert(not second.addItem(other), "Second tab must honor first tab's exclusivity");
assert(other.getLocation() == null and stash.getItemCount() == 1);
assert(select(2, first.transferItemTo(second, kite)), "Moving within one stash must exclude the item's old position");
assert(first.getItemCount() == 0 and second.getItemCount() == 1);
assert(rawequal(kite.getLocation(), second));
assert(not first.addItem(other), "Existing item's restriction must be checked in reverse direction");
assert(not select(2, stash.removeTab(2)) and stash.getTabCount() == 2);
stash.setLocked(true);
assert(not select(2, second.removeItem(kite)) and not first.addItem(other));
stash.setLocked(false);
assert(select(2, stash.removeItem(kite)));
assert(first.addItem(other));
assert(not second.addItem(kite), "Incoming exclusive item's restriction must be checked too");
assert(select(2, stash.clear()) and other.getLocation() == null);
assert(select(2, stash.removeTab(2)) and stash.getTabCount() == 1);
local elsewhere = ItemStashSystem();
assert(select(2, elsewhere.addItem(kite)), "Specific stash scope must not apply to another stash");
assert(select(2, elsewhere.addItem(other)));
local denied = Item({storage = Registry()});
assert(not first.addItem(denied) and denied.getLocation() == null);
local full = ItemSystem(1);
local resident, traveler = Item(), Item();
assert(full.addItem(resident) and first.addItem(traveler));
assert(not select(2, first.transferItemTo(full, traveler)));
assert(first.containsItem(traveler) and full.containsItem(resident));
local _, ok, displaced = first.transferItemTo(full, traveler, true);
assert(ok and rawequal(displaced, resident) and resident.getLocation() == null);
assert(rawequal(traveler.getLocation(), full));
assert(not full.addItem(traveler));
assert(not select(2, full.setMaxItems(0)) and full.getMaxItems() == 1);
local initial = Item();
local system = ItemSystem(2, {initial});
assert(system.containsItemAt(initial, 1) and rawequal(initial.getLocation(), system));
local failedInitial = Item();
assert(not pcall(ItemSystem, 0, {failedInitial}) and failedInitial.getLocation() == null);
assert(not pcall(ItemSystem, 2, {failedInitial, failedInitial}) and failedInitial.getLocation() == null);
local slotA, slotB = ItemSlot(nil, 2), ItemSlot(nil, 2);
local equipment = ItemSlotSystem({slotA, slotB});
local unique = Item({scope = Registry({equipment}), conflicts = Registry({Item})});
assert(select(2, slotA.set(unique)));
assert(not select(2, slotB.set(Item())), "Direct slot calls must enforce system-wide exclusivity");
assert(not select(2, ItemSlotSystem().addItemSlot(slotA)), "Slots cannot belong to two systems");
assert(not select(2, equipment.removeItemSlot(1)), "Nonempty slots cannot be detached");
assert(select(2, equipment.clear()) and unique.getLocation() == null);
assert(select(2, equipment.removeItemSlot(1)) and slotA.getSystem() == null);
local callbackSlot = ItemSlot(ObjectRegistry({Item}, function()
    full.clear();
    return true;
end));
local callbackItem = Item();
assert(not select(2, callbackSlot.set(callbackItem)) and full.containsItem(traveler));
assert(callbackItem.getLocation() == null);
local throwSlot = ItemSlot(ObjectRegistry({Item}, function() error("Callback failure") end));
assert(not select(2, throwSlot.set(callbackItem)) and #throwSlot == 0);
local previewSlot = ItemSlot();
assert(previewSlot.canAccept(callbackItem) and callbackItem.getLocation() == null and #previewSlot == 0);
local gridSlots = {};
for n = 1, 9 do gridSlots[n] = ItemSlot(); end
local grid = ItemSlotSystem(gridSlots);
assert(select(2, grid.configureGrid(3, 3)));
local shape = SlotPattern({{x = 0, y = 0}, {x = 0, y = 1}, {x = 1, y = 1}});
local shaped = Item({pattern = shape});
assert(select(2, grid.placeItem(shaped, 0, 0)));
assert(grid.getItemCount() == 1);
assert(rawequal(grid.getOccupantAt(0, 0), shaped) and rawequal(grid.getOccupantAt(1, 1), shaped));
local blocked = Item();
assert(not select(2, grid.placeItem(blocked, 1, 1)) and blocked.getLocation() == null);
assert(select(2, grid.placeItem(blocked, 2, 0)));
local overEdge = Item({pattern = shape});
assert(not select(2, grid.placeItem(overEdge, 2, 2)) and overEdge.getLocation() == null);
assert(select(2, grid.removeItem(shaped)) and grid.getOccupantAt(1, 1) == nil);
assert(select(2, grid.placeItem(overEdge, 0, 0)));
assert(grid.validate() and stash.validate() and full.validate());
-- A locked reserved cell must prevent operations on the whole footprint.
gridSlots[5].setLocked(true);
assert(not select(2, grid.removeItem(overEdge)));
assert(not select(2, grid.clear()) and grid.getItemCount() == 2);
gridSlots[5].setLocked(false);
assert(select(2, grid.removeItem(overEdge)));
local mutable = SlotPattern({{x = 0, y = 0}});
local mutableItem = Item({pattern = mutable});
assert(select(2, grid.placeItem(mutableItem, 0, 0)));
mutable.setSlots({{x = 0, y = 0}, {x = 0, y = 1}});
assert(rawequal(grid.getOccupantAt(0, 1), mutableItem));
mutable.setSlots({{x = 0, y = 0}, {x = 2, y = 0}});
assert(not grid.validate(), "External pattern edits must not silently overlap");
mutable.setSlots({{x = 0, y = 0}});
assert(grid.validate());
local actor, outsider = Item(), Item();
local permissions = ObjectRegistry({actor});
local host = Item({attach = ObjectRegistry({BaseItem}), detach = permissions});
local gem = Item({attach = ObjectRegistry({host}), detach = permissions});
assert(select(2, gem.attachTo(host)) and rawequal(gem.getAttached_To(), host));
local count = 0;
for _, attached in host.eachAttachment() do assert(rawequal(attached, gem)); count = count + 1; end
assert(count == 1);
assert(not first.addItem(gem), "Attached items cannot be stored as separate contents");
assert(not select(2, host.attachTo(gem)), "Attachment cycles must be rejected");
assert(not select(2, gem.detach(outsider)) and select(2, gem.detach(actor)));
assert(gem.getAttached_To() == null);
count = 0;
for _ in host.eachAttachment() do count = count + 1; end
assert(count == 0);
assert(select(2, gem.attachTo(host)) and select(2, gem.detach(actor)), "Optional references must support repeated attach/detach");
local potion = Item({consume = permissions, remove = permissions});
local potions = ItemSlot(nil, 2);
local spare = Item({consume = permissions});
assert(select(2, potions.set(potion)) and select(2, potions.set(spare)));
assert(not select(2, potions.consumeItem(potion, outsider)));
assert(select(2, potions.consumeItem(potion, actor)) and #potions == 1 and potion.getLocation() == null);
assert(rawequal(potions.get(), spare), "Consuming one instance must preserve the rest of a stack");
local gear = Item({equip = permissions, unequip = permissions, tradeBy = permissions, tradeTo = ObjectRegistry({outsider})});
local equip = ItemSlotSystem({ItemSlot()});
assert(first.addItem(gear));
assert(not select(2, equip.equipItem(gear, outsider, 1)) and first.containsItem(gear));
assert(select(2, equip.equipItem(gear, actor, 1)) and not first.containsItem(gear));
assert(not select(2, equip.unequipItem(gear, outsider, first)));
assert(select(2, equip.unequipItem(gear, actor, first)) and first.containsItem(gear));
local recipient = ItemSystem(2);
assert(not select(2, first.tradeItemTo(recipient, gear, outsider, actor)));
assert(select(2, first.tradeItemTo(recipient, gear, actor, outsider)) and recipient.containsItem(gear));
local specificScope = Item({scope = stash});
assert(specificScope.getExclusive_In().allows(stash));
local bypassSlot = ItemSlot(ObjectRegistry({Item}, function()
    traveler.setLocation(null, full);
    return true;
end));
assert(not select(2, bypassSlot.set(Item())) and rawequal(traveler.getLocation(), full));
local tabWithConflict = ItemSystem();
local stashWithRule = ItemStashSystem();
local ownerOfRule = Item({scope = Registry({stashWithRule}), conflicts = Registry({Item})});
assert(select(2, stashWithRule.addItem(ownerOfRule)));
assert(tabWithConflict.addItem(Item()));
assert(not select(2, stashWithRule.addTab(tabWithConflict)) and tabWithConflict.getStash() == null);
assert(stashWithRule.getTabCount() == 1 and tabWithConflict.getItemCount() == 1);
assert(not pcall(serialize, ItemSlot()), "Unsupported container snapshots must fail explicitly rather than lose contents");
assert(not pcall(clone, ItemSystem()), "Implicit container copying must not alias live membership");
local owned = ItemSlotSystem({ItemSlot()}, actor);
assert(rawequal(owned.getItemSlotAt(1).getOwner(), actor));
local ownedStash = ItemStashSystem(actor);
assert(rawequal(ownedStash.getTab(1).getOwner(), actor));
assert(select(2, gem.attachTo(host)));
count = 0;
for _ in BaseItem.eachAttachmentOf(host) do count = count + 1; end
assert(count == 1 and select(2, gem.detach(actor)));
print("PASS complete item system: stash-wide bidirectional exclusivity, direct-tab/slot enforcement, capacity, identity, atomic transfers/replacement/clear, location, ownership, callback isolation and grid footprints");
